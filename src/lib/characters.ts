export interface QuestSection {
  heading: string;
  body: string;
}

export interface GalleryImage {
  src: string;
  alt: string;
}

export type GalleryItem = GalleryImage | Embed;

export interface CTA {
  label: string;
  href: string;
}

export interface QuestDetails {
  client?: string;
  role?: string;
  timeframe?: string;
  situation?: string;
  approach?: string;
  workItems?: string[];
  metrics?: { label: string; value: string }[];
  embeds?: Embed[];
  gallery?: GalleryItem[];
  /** Free-form image cards rendered at their natural aspect ratio (e.g. portrait analytics screenshots). */
  shots?: GalleryImage[];
  pressLinks?: { label: string; url: string }[];
  testimonials?: string[];
  substackPosts?: { title: string; url: string; image: string }[];
  // legacy/extra
  summary?: string;
  sections?: QuestSection[];
}

export interface Chapter {
  slug?: string;
  href?: string;
  title: string;
  meta: string;
  description: string;
  tags: string[];
  /** Shorter goal copy used only on the character-page quest card; falls back to `goal`. */
  cardGoal?: string;
  goal?: string;
  outcome?: string;
  outcomeMeta?: string;
  details?: QuestDetails;
  /** Final CTAs rendered centered at the bottom of the quest page. */
  ctas?: CTA[];
}

